# Make exactly 150 questions while keeping all knowledge groups.
# Every group has at least two phrasings; the first 32 groups get a third.
qs=[]
for idx,f in enumerate(facts):
    assert len(f['stems'])==3
    take = 3 if idx < 32 else 2
    for i,stem in enumerate(f['stems'][:take],1):
        qs.append({
            'id':f"{f['g']}-{i}", 'group':f['g'], 'difficulty':f['d'], 'category':f['cat'],
            'question':stem, 'answers':f['opts'], 'correct':f['a'], 'explanation':f['exp']
        })
assert len(qs)==150, len(qs)
out=pathlib.Path(__file__).parent/'data'/'questions.json'
out.write_text(json.dumps(qs,ensure_ascii=False,indent=2),encoding='utf-8')
print(f'wrote {len(qs)} questions / {len(facts)} knowledge groups -> {out}')
